#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';

const mode = String(process.argv[2] || '').trim().toLowerCase();
const validModes = new Set(['cnhk', 'global']);
if (!validModes.has(mode)) {
  console.error('Usage: node scripts/setup-network-profile.mjs <cnhk|global>');
  process.exit(1);
}

const rootDir = process.cwd();
const envPath = path.join(rootDir, '.env.local');

const parseEnv = (raw) => {
  const map = new Map();
  const lines = String(raw || '').split(/\r?\n/);
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const idx = trimmed.indexOf('=');
    if (idx <= 0) continue;
    const key = trimmed.slice(0, idx).trim();
    let value = trimmed.slice(idx + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    map.set(key, value);
  }
  return map;
};

const getExistingEnv = () => {
  try {
    return parseEnv(fs.readFileSync(envPath, 'utf8'));
  } catch {
    return new Map();
  }
};

const existing = getExistingEnv();
const getValue = (key, fallback = '') => {
  const current = String(existing.get(key) || '').trim();
  return current || fallback;
};

const buildProfile = () => {
  if (mode === 'cnhk') {
    return {
      VITE_AI_PROVIDER: 'deepseek',
      VITE_DEEPSEEK_API_KEY: getValue('VITE_DEEPSEEK_API_KEY'),
      VITE_DEEPSEEK_MODEL: getValue('VITE_DEEPSEEK_MODEL', 'deepseek-chat'),
      VITE_DEEPSEEK_ENDPOINT: getValue('VITE_DEEPSEEK_ENDPOINT', 'https://api.deepseek.com'),
      VITE_GEMINI_API_KEY: getValue('VITE_GEMINI_API_KEY'),
      VITE_GEMINI_MODEL: getValue('VITE_GEMINI_MODEL', 'google/gemini-2.5-flash'),
      VITE_GEMINI_ENDPOINT: getValue('VITE_GEMINI_ENDPOINT', 'https://openrouter.ai/api/v1'),
      VITE_OPENROUTER_API_KEY: getValue('VITE_OPENROUTER_API_KEY'),
      VITE_CHARACTER_IMAGE_MODEL: getValue('VITE_CHARACTER_IMAGE_MODEL', 'google/gemini-3.1-flash-image-preview'),
      VITE_CHARACTER_IMAGE_ENDPOINT: getValue('VITE_CHARACTER_IMAGE_ENDPOINT', 'https://openrouter.ai/api/v1'),
      VITE_ENABLE_REMOTE_TTS: '0',
      VITE_REMOTE_TTS_API_KEY: getValue('VITE_REMOTE_TTS_API_KEY', getValue('VITE_OPENROUTER_API_KEY')),
      VITE_TTS_STRICT_TEXT_SYNC: getValue('VITE_TTS_STRICT_TEXT_SYNC', '1'),
      VITE_TTS_DEBUG: getValue('VITE_TTS_DEBUG', '1'),
      VITE_REMOTE_TTS_ENDPOINT: getValue('VITE_REMOTE_TTS_ENDPOINT', 'https://openrouter.ai/api/v1'),
      VITE_REMOTE_TTS_MODEL: getValue('VITE_REMOTE_TTS_MODEL', 'openai/gpt-audio-mini'),
      VITE_REMOTE_TTS_VOICE: getValue('VITE_REMOTE_TTS_VOICE', 'alloy'),
      VITE_REMOTE_TTS_FORMAT: getValue('VITE_REMOTE_TTS_FORMAT', 'pcm16'),
    };
  }

  return {
    VITE_AI_PROVIDER: getValue('VITE_AI_PROVIDER', 'gemini'),
    VITE_DEEPSEEK_API_KEY: getValue('VITE_DEEPSEEK_API_KEY'),
    VITE_DEEPSEEK_MODEL: getValue('VITE_DEEPSEEK_MODEL', 'deepseek-chat'),
    VITE_DEEPSEEK_ENDPOINT: getValue('VITE_DEEPSEEK_ENDPOINT', 'https://api.deepseek.com'),
    VITE_GEMINI_API_KEY: getValue('VITE_GEMINI_API_KEY'),
    VITE_GEMINI_MODEL: getValue('VITE_GEMINI_MODEL', 'google/gemini-2.5-flash'),
    VITE_GEMINI_ENDPOINT: getValue('VITE_GEMINI_ENDPOINT', 'https://openrouter.ai/api/v1'),
    VITE_OPENROUTER_API_KEY: getValue('VITE_OPENROUTER_API_KEY'),
    VITE_CHARACTER_IMAGE_MODEL: getValue('VITE_CHARACTER_IMAGE_MODEL', 'google/gemini-3.1-flash-image-preview'),
    VITE_CHARACTER_IMAGE_ENDPOINT: getValue('VITE_CHARACTER_IMAGE_ENDPOINT', 'https://openrouter.ai/api/v1'),
    VITE_ENABLE_REMOTE_TTS: getValue('VITE_ENABLE_REMOTE_TTS', '1'),
    VITE_REMOTE_TTS_API_KEY: getValue('VITE_REMOTE_TTS_API_KEY', getValue('VITE_OPENROUTER_API_KEY')),
    VITE_TTS_STRICT_TEXT_SYNC: getValue('VITE_TTS_STRICT_TEXT_SYNC', '1'),
    VITE_TTS_DEBUG: getValue('VITE_TTS_DEBUG', '1'),
    VITE_REMOTE_TTS_ENDPOINT: getValue('VITE_REMOTE_TTS_ENDPOINT', 'https://openrouter.ai/api/v1'),
    VITE_REMOTE_TTS_MODEL: getValue('VITE_REMOTE_TTS_MODEL', 'openai/gpt-audio-mini'),
    VITE_REMOTE_TTS_VOICE: getValue('VITE_REMOTE_TTS_VOICE', 'alloy'),
    VITE_REMOTE_TTS_FORMAT: getValue('VITE_REMOTE_TTS_FORMAT', 'pcm16'),
  };
};

const profile = buildProfile();
const outputLines = [
  `# Auto-generated by scripts/setup-network-profile.mjs (${mode})`,
  '# Review and update API keys if needed.',
  ...Object.entries(profile).map(([k, v]) => `${k}=${String(v ?? '')}`),
  '',
];

fs.writeFileSync(envPath, outputLines.join('\n'), 'utf8');

console.log(`Generated .env.local with '${mode}' network profile.`);
console.log(`Path: ${envPath}`);
