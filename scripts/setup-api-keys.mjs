#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';

/**
 * Fill your API keys in CONFIG, then run: npm run setup:api
 */
const CONFIG = {
  provider: 'gemini', // deepseek | gemini

  deepseek: {
    apiKey: 'your api key',
    model: 'deepseek-chat',
    endpoint: 'https://api.deepseek.com/chat/completions',
  },

  gemini: {
    apiKey: 'your api key',
    openrouterApiKey: 'your api key',
    model: 'google/gemini-2.5-flash',
    endpoint: 'https://openrouter.ai/api/v1',
    characterImageModel: 'google/gemini-3.1-flash-image-preview',
    characterImageEndpoint: 'https://openrouter.ai/api/v1',
  },
};

const rootDir = process.cwd();
const envPath = path.join(rootDir, '.env.local');

const normalizedProvider = String(CONFIG.provider || 'gemini').trim().toLowerCase();
const validProvider = ['deepseek', 'gemini'].includes(normalizedProvider)
  ? normalizedProvider
  : 'gemini';

const lines = [
  '# Auto-generated by scripts/setup-api-keys.mjs',
  `VITE_AI_PROVIDER=${validProvider}`,
  `VITE_DEEPSEEK_API_KEY=${String(CONFIG.deepseek?.apiKey || '').trim()}`,
  `VITE_DEEPSEEK_MODEL=${String(CONFIG.deepseek?.model || 'deepseek-chat').trim()}`,
  `VITE_DEEPSEEK_ENDPOINT=${String(CONFIG.deepseek?.endpoint || 'https://api.deepseek.com/chat/completions').trim()}`,
  `VITE_GEMINI_API_KEY=${String(CONFIG.gemini?.apiKey || '').trim()}`,
  `VITE_GEMINI_MODEL=${String(CONFIG.gemini?.model || 'google/gemini-2.5-flash').trim()}`,
  `VITE_GEMINI_ENDPOINT=${String(CONFIG.gemini?.endpoint || 'https://openrouter.ai/api/v1').trim()}`,
  `VITE_OPENROUTER_API_KEY=${String(CONFIG.gemini?.openrouterApiKey || '').trim()}`,
  `VITE_CHARACTER_IMAGE_MODEL=${String(CONFIG.gemini?.characterImageModel || 'google/gemini-3.1-flash-image-preview').trim()}`,
  `VITE_CHARACTER_IMAGE_ENDPOINT=${String(CONFIG.gemini?.characterImageEndpoint || 'https://openrouter.ai/api/v1').trim()}`,
  `VITE_REMOTE_TTS_API_KEY=${String(CONFIG.gemini?.openrouterApiKey || '').trim()}`,
  `VITE_REMOTE_TTS_ENDPOINT=https://openrouter.ai/api/v1`,
  `VITE_REMOTE_TTS_MODEL=openai/gpt-audio-mini`,
  `VITE_REMOTE_TTS_VOICE=alloy`,
  `VITE_REMOTE_TTS_FORMAT=pcm16`,
  '',
];

fs.writeFileSync(envPath, lines.join('\n'), 'utf8');

console.log('Generated .env.local');
console.log(`Path: ${envPath}`);
console.log(`Provider: ${validProvider}`);
console.log('Update CONFIG and run npm run setup:api again to overwrite values.');
